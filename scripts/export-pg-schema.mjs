import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const folder = path.join(root, "apps/web/src/lib/db/pg-migrations");
const journal = JSON.parse(fs.readFileSync(path.join(folder, "meta/_journal.json"), "utf8"));
const entries = journal.entries.map((entry) => {
  const source = fs.readFileSync(path.join(folder, `${entry.tag}.sql`), "utf8");
  return { ...entry, source, hash: createHash("sha256").update(source).digest("hex") };
});
const source = `-- Generated by node scripts/export-pg-schema.mjs. Apply only to a new astronom schema.\n` +
  entries.map((entry) => entry.source).join("\n") + `
CREATE TABLE astronom.__drizzle_migrations (id serial PRIMARY KEY, hash text NOT NULL, created_at bigint NOT NULL);
ALTER TABLE astronom.__drizzle_migrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON astronom.__drizzle_migrations FROM PUBLIC;
INSERT INTO astronom.__drizzle_migrations (hash, created_at) VALUES
${entries.map((entry) => `('${entry.hash}', ${entry.when})`).join(",\n")};
`;
fs.writeFileSync(path.join(root, "supabase/core-schema.sql"), source);
console.log(`Exported ${entries.length} core Postgres migrations.`);
